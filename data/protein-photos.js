// Commons serves a resized copy (1100 px wide) of the original through Special:FilePath.
export function commonsPhoto(id, alt) {
  const entry = photoCredits[id];
  if (!entry) throw new Error(`No photo credit for ${id}`);
  const [file, author, license] = entry;
  const page = `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file)}`;
  return {
    src: `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file)}?width=1100`,
    alt, author, license, sourceUrl: page,
    ...(LICENSE_URLS[license] ? { licenseUrl: LICENSE_URLS[license] } : {}),
    caption: 'Real photo from Wikimedia Commons, showing the dish. The plate pictured may differ from this recipe.',
  };
}
